/**
 * Кто отвечает на какой запрос.
 *
 * Модуль намеренно не знает ни про сеть, ни про SDK: это чистый выбор
 * из списка, и проверять его надо тестами, а не живыми вызовами. Пока он
 * жил внутри model.ts, собрать его в тест было нельзя — сборка тянула
 * клиент Gemini, а тот при импорте требует child_process.
 *
 * Смысл ротации в устройстве бесплатных тарифов: у Gemini суточная квота
 * считается ОТДЕЛЬНО по каждой модели, поэтому четыре модели — это четыре
 * независимых кармана, а не один общий. У Groq квота на порядки больше,
 * но ограничение стоит на токенах в минуту.
 */

export type Provider = "gemini" | "groq";

export interface ModelRef {
  provider: Provider;
  model: string;
}

/**
 * Модели Groq, проверенные на ДОСЛОВНОЕ цитирование русского текста.
 *
 * Это не украшение списка: код сверяет цитату с текстом страницы и
 * отбрасывает материал, если её там нет. Модель, которая пересказывает
 * своими словами, тратит вызов впустую.
 *
 * Проверка живым запросом: gpt-oss-120b и qwen3.8-27b цитируют дословно,
 * а gpt-oss-20b переписала «считают» в «считаются» и обрезала фразу —
 * её здесь нет намеренно.
 *
 * Порядок не случаен. gpt-oss-120b стабильно берёт пачку из четырёх страниц
 * за 6–7 секунд, а qwen на том же объёме отвечает 429 даже после повторов:
 * у него на бесплатном тарифе заметно меньше токенов в минуту.
 */
export const GROQ_MODELS = ["openai/gpt-oss-120b", "qwen/qwen3.8-27b"];

/**
 * Модели одного класса для параллельной работы. Класс один (flash), поэтому
 * строгость разбора между ними не расходится, а квота у каждой своя.
 */
export const FLASH_MODELS = ["gemini-3.8-flash", "gemini-3.7-flash", "gemini-3.6-flash", "gemini-3.5-flash"];

/**
 * Лёгкая модель для вспомогательных шагов. Квота у неё на порядок больше,
 * чем 20 запросов в сутки у флагманской.
 */
export const FAST_MODEL = "gemini-3.1-flash-lite";

export function hasGroq(): boolean {
  return Boolean(process.env.GROQ_API_KEY);
}

/**
 * Ротация Gemini, начинающаяся с выбранной пользователем модели. Его выбор
 * из брифа обязан идти первым, остальные — запасные карманы квоты.
 */
export function rotationFor(model: string): string[] {
  /*
   * Лёгкая модель замыкает очередь, а не стоит в стороне.
   *
   * Её тут не было, и это стоило прогонов: у флагманских flash суточная
   * квота 20 запросов на каждую, а у lite — на порядок больше. Когда все
   * четыре flash выбраны, lite почти наверняка ещё жива, и шаг с большим
   * входом, который Groq не возьмёт по лимиту токенов в минуту, ей вполне
   * по силам: контекст у неё тот же.
   *
   * Последней, потому что русский слог у неё слабее: пока есть flash,
   * пишет flash.
   */
  return [model, ...FLASH_MODELS.filter((m) => m !== model), FAST_MODEL];
}

function groqRefs(): ModelRef[] {
  return hasGroq() ? GROQ_MODELS.map((m) => ({ provider: "groq" as const, model: m })) : [];
}

/**
 * Очередь для РАЗБОРА страниц. Groq впереди: у него суточный лимит на три
 * порядка больше, а на замере пачка разбиралась секунды вместо минут.
 * Gemini остаётся в хвосте на случай, если ключа Groq нет или он отказал.
 */
export function siftRotation(model: string): ModelRef[] {
  return [...groqRefs(), ...rotationFor(model).map((m) => ({ provider: "gemini" as const, model: m }))];
}

/**
 * Очередь для НАПИСАНИЯ контента. Порядок обратный: русский текст голосом
 * владельца пишет Gemini, и только когда его суточная квота кончится, тема
 * уходит на Groq — лучше другой стиль, чем пустой слот.
 */
export function writeRotation(model: string, index = 0): ModelRef[] {
  const gemini = rotationFor(model).map((m) => ({ provider: "gemini" as const, model: m }));
  // Каждая тема начинает со СВОЕЙ модели: темы пишутся параллельно, и три
  // запроса подряд к одной модели стоили бы трёх из одной суточной квоты
  // вместо одного из трёх разных карманов.
  const start = index % gemini.length;
  const mine = gemini.slice(start).concat(gemini.slice(0, start));
  // Только две модели Gemini, дальше сразу Groq: при очереди из четырёх
  // первая тема до запасного провайдера просто не доходила — попытки
  // заканчивались раньше.
  return [...mine.slice(0, 2), ...groqRefs(), { provider: "gemini" as const, model: FAST_MODEL }];
}

/**
 * Сколько моделей в начале очереди имеют большую квоту. Пачки распределяются
 * по кругу именно по ним: иначе лишняя пачка уходит на Gemini и падает на
 * исчерпанной квоте, хотя у Groq лимит и не думал кончаться.
 */
export function abundantCount(refs: ModelRef[]): number {
  const n = refs.filter((r) => r.provider === "groq").length;
  return n > 0 ? n : refs.length;
}

/**
 * Сколько пачек можно запускать одновременно. У Groq лимит считается в
 * токенах за минуту и ОБЩИЙ на ключ, поэтому две пачки разом его пробивают:
 * на замере одна проходила за 6 секунд, а вторая получала 429. Когда работа
 * идёт через Groq, пачки выстраиваются в очередь — он настолько быстрее,
 * что три пачки подряд всё равно занимают около двадцати секунд против
 * двух-четырёх минут, которые тот же отбор занимал на Gemini.
 */
export function lanesFor(refs: ModelRef[]): number {
  return refs[0]?.provider === "groq" ? 1 : Math.max(1, refs.length);
}

/**
 * Сколько знаков запроса Groq берёт на бесплатном тарифе.
 *
 * Лимит там считается в токенах за минуту, и большой запрос он отвергает
 * с 413 или 429 ещё до всякой работы. Замеры: 13 тысяч знаков проходят
 * за 5–8 секунд, 21 тысяча отвергается. Ставим 16 000 с запасом.
 */
export const GROQ_INPUT_LIMIT = 16_000;

/**
 * Очередь под запрос конкретного размера. Заведомо большой запрос к Groq
 * не отправляем: отказ по размеру стоит времени, но ничего не проверяет.
 * Если после отсева не осталось никого — возвращаем исходную очередь,
 * потому что попробовать и получить внятную ошибку лучше, чем молча
 * отказаться от работы.
 */
export function queueForSize(order: ModelRef[], chars: number): ModelRef[] {
  if (chars <= GROQ_INPUT_LIMIT) return order;
  const withoutGroq = order.filter((r) => r.provider !== "groq");
  return withoutGroq.length ? withoutGroq : order;
}

/** Как называть модель человеку в логе: провайдер важен, префикс пути — нет. */
export function refLabel(ref: ModelRef): string {
  return ref.provider === "groq" ? `groq/${ref.model.split("/").pop()}` : ref.model;
}
