import { refFromName, refLabel } from "./rotation";

/**
 * Сказать один раз за прогон, что выбранная модель кончилась.
 *
 * Подмена работает молча и правильно: очередь переходит к следующей модели
 * за доли секунды, прогон не прерывается. Но владелец при этом не знает
 * главного — что русский текст сегодня пишет запасная модель, а у неё слог
 * суше. Узнавать это по смене имени в строке «Выпуск написал …» значит
 * догадываться.
 *
 * Условий два, и оба обязательны.
 *
 * Первое: сообщать только про ВЫБРАННУЮ модель. Механические шаги уходят
 * на Groq по замыслу, а не от нехватки квоты, и «Gemini кончился» там было
 * бы враньём.
 *
 * Второе: только про СУТОЧНУЮ квоту. Минутный лимит проходит сам за
 * несколько секунд, и следующий вызов та же модель возьмёт как ни в чём
 * не бывало — объявлять из-за него, что запасные модели работают «дальше»,
 * было бы неправдой. Отказ по сети или по формату — тем более другой повод.
 *
 * Один раз за прогон, потому что вызовов у прогона пять, а новость одна.
 */
export function createQuotaNotice(primary: string): (failures: string[]) => string | null {
  const label = refLabel(refFromName(primary));
  let told = false;

  return (failures) => {
    if (told) return null;
    // Строка отказа собрана как «имя — причина»; ищем свою по имени.
    const own = failures.find((f) => f.startsWith(`${label} —`));
    // «суточная квота при этом цела» — это текст про МИНУТНЫЙ лимит, и слово
    // «суточная» в нём есть. Поэтому одного вхождения мало.
    if (!own || !/суточн/i.test(own) || /минутн/i.test(own)) return null;
    told = true;
    return `${label}: суточная квота на сегодня выбрана — дальше работают запасные модели, слог будет суше.`;
  };
}
