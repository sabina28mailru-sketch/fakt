/**
 * Ошибки внешних сервисов на человеческом языке.
 *
 * Сюда они попадают сырыми — телом ответа, кодом состояния, английским
 * текстом библиотеки, — а наружу должны выходить фразой, по которой
 * владелец поймёт, что делать. В логе конвейера висело буквально это:
 *
 *   Tavily ответил 401: { "detail": { "error": "Unauthorized: missing
 *   or invalid API key." } }
 *
 * И так двенадцать раз подряд, по разу на запрос. Человек, который
 * собирает контент, не обязан читать JSON, чтобы узнать, что ключ не
 * принят. Тело ответа не показываем вовсе: оно ничего не добавляет к
 * коду состояния, но занимает весь экран.
 *
 * Модуль намеренно чистый: ни сети, ни SDK — только текст, и проверять
 * его надо тестами.
 */

/** Почему поиск отказал. Тело ответа сюда не попадает намеренно. */
export function searchError(status: number): string {
  if (status === 401 || status === 403) {
    return "Ключ Tavily не принят. Проверьте TAVILY_API_KEY — на бессерверном хостинге он задаётся в настройках проекта, локально в .env.local.";
  }
  if (status === 429) {
    return "Tavily отвечает слишком часто — минутный лимит. Проходит сам, повтор уже встроен.";
  }
  // 432 и 433 у Tavily — про исчерпанный тариф, а не про скорость.
  if (status === 432 || status === 433) {
    return "Кредиты Tavily на этот месяц кончились. Новые начисляются в начале месяца, или можно поднять тариф на tavily.com.";
  }
  if (status >= 500) {
    return "Tavily не отвечает — это на их стороне. Стоит повторить позже.";
  }
  return `Поиск отказал, код ${status}.`;
}

/**
 * Почему страница не открылась.
 *
 * Причины приходят от нескольких источников на английском: от Tavily,
 * от самого сайта, от сетевого слоя. Различать их в интерфейсе незачем —
 * важно одно: виноват сайт, а не настройка, и делать тут нечего.
 */
export function pageError(raw: string): string {
  const t = raw.toLowerCase();
  if (/timeout|timed out|abort/.test(t)) return "сайт не ответил вовремя";
  if (/403|forbidden|denied|captcha|cloudflare/.test(t)) return "сайт закрыт для автоматического чтения";
  if (/404|not found/.test(t)) return "страницы больше нет";
  if (/too short|слишком коротк|empty/.test(t)) return "на странице почти нет текста";
  if (/failed to fetch|fetch failed|econnreset|network|dns|enotfound/.test(t)) return "сайт не отдал страницу";
  if (/paywall|subscription/.test(t)) return "материал за подпиской";
  return "не открылась";
}
