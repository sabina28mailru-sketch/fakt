/**
 * Документное хранилище: общий интерфейс для файлов и базы.
 *
 * Зачем разделение. Локально приложение работает на файлах в data/ — их
 * можно открыть редактором, а git ведёт историю вместе с кодом. На
 * бессерверном хостинге файловая система доступна только для чтения и
 * обнуляется при каждом запуске, поэтому там нужна база.
 *
 * Разница спрятана здесь, и только здесь. Четырнадцать функций хранилища
 * написаны один раз поверх этого интерфейса: дублировать их для каждого
 * способа хранения значило бы чинить любую правку дважды.
 */

/** Что храним. Каждый вид лежит отдельно и перечисляется независимо. */
export type DocKind = "edition" | "feed" | "settings" | "research" | "usage";

/** Виды, у которых ровно один документ: ключ совпадает с именем вида. */
export const SINGLETONS: DocKind[] = ["settings", "research", "usage"];

export interface DocStore {
  /** Документ по ключу или null, если его нет или он не читается. */
  get(kind: DocKind, key: string): Promise<unknown | null>;
  put(kind: DocKind, key: string, value: unknown): Promise<void>;
  /** Ключи вида, отсортированные по убыванию: свежие первыми. */
  keys(kind: DocKind): Promise<string[]>;
  /**
   * Документы вида, свежие первыми. Битые пропускаются молча — так же,
   * как это делало файловое хранилище: один испорченный выпуск не должен
   * ронять всю историю.
   */
  list(kind: DocKind, limit?: number): Promise<unknown[]>;
}
